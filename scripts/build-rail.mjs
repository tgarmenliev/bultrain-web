// Builds src/data/bg-rail.js (the railway lines drawn on the phone map) from the track geometry of the public
// GTFS static feed. Run after the network changes:
//   node scripts/build-rail.mjs <folder with shapes.txt>
// Thousands of trips share the same track, so only the parts not already drawn are kept, then simplified.
import { createReadStream, writeFileSync } from 'node:fs'
import { createInterface } from 'node:readline'
import { join } from 'node:path'
import { project, BG_SIZE } from '../src/data/bg-outline.js'

const dir = process.argv[2]
if (!dir) throw new Error('usage: node scripts/build-rail.mjs <folder with shapes.txt>')
const TOL = 3.2 // map units (~1.6 km): closer than this to a drawn line = the same line
const EPS = 0.7 // simplification
const MARGIN = 6
const HOLE = 16 // a skipped straight jump is drawn after all if somewhere along it there is no real track this close
const MAX_GAP = 34 // some trips jump straight between far points; such chords are skipped (other trips have the real track)

const shapes = new Map()
let head = null
for await (const line of createInterface({ input: createReadStream(join(dir, 'shapes.txt')) })) {
  const c = line.split(',')
  if (!head) { head = Object.fromEntries(c.map((k, i) => [k.replace(/^﻿/, ''), i])); continue }
  const id = c[head.shape_id]
  const [x, y] = project(+c[head.shape_pt_lon], +c[head.shape_pt_lat])
  if (!shapes.has(id)) shapes.set(id, [])
  shapes.get(id).push([+c[head.shape_pt_sequence], x, y])
}

// distinct geometries only, longest first
const seen = new Set()
const lines = []
const chords = []
for (const pts of shapes.values()) {
  pts.sort((a, b) => a[0] - b[0])
  const key = pts.map((p) => `${p[1].toFixed(0)},${p[2].toFixed(0)}`).join(';')
  if (seen.has(key)) continue
  seen.add(key)
  let dense = []
  for (let i = 1; i < pts.length; i++) {
    const [, ax, ay] = pts[i - 1]
    const [, bx, by] = pts[i]
    const gap = Math.hypot(bx - ax, by - ay)
    if (gap > MAX_GAP) { if (gap <= MAX_GAP * 3) chords.push([[ax, ay], [bx, by], gap]); if (dense.length) lines.push(dense); dense = []; continue }
    const n = Math.max(1, Math.ceil(gap))
    for (let k = dense.length ? 1 : 0; k <= n; k++) dense.push([ax + ((bx - ax) * k) / n, ay + ((by - ay) * k) / n])
  }
  if (dense.length) lines.push(dense)
}
lines.sort((a, b) => b.length - a.length)

const grid = new Map()
const cell = (x, y) => `${Math.floor(x / TOL)},${Math.floor(y / TOL)}`
const covered = ([x, y]) => {
  const cx = Math.floor(x / TOL)
  const cy = Math.floor(y / TOL)
  for (let i = -1; i <= 1; i++) for (let j = -1; j <= 1; j++) for (const [px, py] of grid.get(`${cx + i},${cy + j}`) ?? []) if (Math.hypot(px - x, py - y) < TOL) return true
  return false
}
const add = (p) => { const k = cell(...p); if (!grid.has(k)) grid.set(k, []); grid.get(k).push(p) }

function simplify(p) {
  if (p.length < 3) return p
  const [ax, ay] = p[0]
  const [bx, by] = p[p.length - 1]
  const len = Math.hypot(bx - ax, by - ay)
  let far = 0
  let at = 0
  for (let i = 1; i < p.length - 1; i++) {
    const [x, y] = p[i]
    const d = len ? Math.abs((bx - ax) * (ay - y) - (ax - x) * (by - ay)) / len : Math.hypot(x - ax, y - ay)
    if (d > far) { far = d; at = i }
  }
  return far > EPS ? [...simplify(p.slice(0, at + 1)).slice(0, -1), ...simplify(p.slice(at))] : [p[0], p[p.length - 1]]
}

const runs = []
for (const line of lines) {
  const fresh = line.map((p) => !covered(p))
  for (let i = 0; i < line.length; i++) {
    if (!fresh[i]) continue
    let j = i
    while (j + 1 < line.length && fresh[j + 1]) j++
    const run = line.slice(Math.max(0, i - 4), Math.min(line.length, j + 5)) // overlap a little so lines connect
    if (j - i >= 3) { runs.push(run); run.forEach(add) }
    i = j
  }
}

// second pass: fill the real holes (track that only exists in the feed as a long straight jump)
const drawn = runs.flat()
const nearest = (x, y) => drawn.reduce((m, [px, py]) => Math.min(m, Math.hypot(px - x, py - y)), Infinity)
for (const [a, b, gap] of chords.sort((p, q) => p[2] - q[2])) {
  const n = Math.ceil(gap)
  const pts = Array.from({ length: n + 1 }, (_, k) => [a[0] + ((b[0] - a[0]) * k) / n, a[1] + ((b[1] - a[1]) * k) / n])
  if (pts.some(([x, y]) => nearest(x, y) > HOLE)) { runs.push(pts); drawn.push(...pts) }
}

const inside = ([x, y]) => x > -MARGIN && y > -MARGIN && x < BG_SIZE.width + MARGIN && y < BG_SIZE.height + MARGIN
const f = (n) => Math.round(n * 10) / 10
const d = runs.map((r) => simplify(r.filter(inside))).filter((r) => r.length > 1)
  .map((r) => `M${f(r[0][0])} ${f(r[0][1])}L${r.slice(1).map(([x, y]) => `${f(x)} ${f(y)}`).join(' ')}`).join('')

writeFileSync('src/data/bg-rail.js', `// GENERATED by scripts/build-rail.mjs from the track geometry of the public GTFS static feed. Do not edit.\nexport const BG_RAIL = '${d}'\n`)
console.log(`${shapes.size} shapes -> ${seen.size} distinct -> ${runs.length} segments, ${(d.length / 1024).toFixed(1)} KB`)
